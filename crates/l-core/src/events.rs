//! Events pushed from background services back into the app.

use crate::models::{
    ChannelEntry, ChatMessage, DiscordAccount, GuildInfo, Layout, Note, Notification, PlacedWidget,
    VoiceInfo, WidgetInstanceId,
};
use crate::state::{AuditEntry, Preferences};
use serde_json::Value;

/// Events emitted by services (storage, discord, runtime) on channels.
#[derive(Debug, Clone)]
pub enum AppEvent {
    /// Initial hydration completed.
    Hydrated(Box<HydratedData>),
    /// Preferences changed externally.
    PreferencesChanged(Box<Preferences>),
    /// Discord OAuth completed.
    OAuthCompleted {
        /// Whether it succeeded.
        ok: bool,
        /// Error message on failure.
        error: Option<String>,
    },
    /// Discord account + guilds fetched.
    DiscordDataFetched {
        /// Account profile.
        account: Option<DiscordAccount>,
        /// Guild list.
        guilds: Vec<GuildInfo>,
        /// Granted scopes.
        scopes: Vec<String>,
    },
    /// Bot verification result.
    BotVerified {
        /// Success flag.
        ok: bool,
        /// Bot user id.
        bot_user_id: Option<String>,
        /// Bot username.
        bot_username: Option<String>,
        /// Error.
        error: Option<String>,
    },
    /// A Discord REST response payload.
    RestResponse {
        /// Request tag echoed back.
        tag: String,
        /// HTTP status.
        status: u16,
        /// JSON body.
        body: Value,
    },
    /// REST request failed.
    RestFailed {
        /// Request tag.
        tag: String,
        /// Error message.
        error: String,
    },
    /// Widget data snapshot published by the data hub.
    WidgetData {
        /// Instance id.
        id: WidgetInstanceId,
        /// Need key that produced it.
        need: String,
        /// JSON payload.
        data: Value,
    },
    /// Widget fetch failed.
    WidgetFailed {
        /// Instance id.
        id: WidgetInstanceId,
        /// Error.
        error: String,
    },
    /// File chosen via native dialog for import.
    FileChosen {
        /// Path.
        path: std::path::PathBuf,
    },
    /// File chosen for export.
    ExportFileChosen {
        /// Path.
        path: std::path::PathBuf,
    },
    /// Generic info toast from a service.
    ServiceToast {
        /// Text.
        text: String,
        /// Severity word.
        kind: String,
    },
    /// A new notification was generated by an integration.
    NewNotification(Box<Notification>),
    /// Gateway session state changed (bot websocket).
    GatewayUpdate {
        /// Human-readable state (e.g. `connected`, `reconnecting`).
        state: String,
        /// Approximate latency ms, if known.
        latency_ms: Option<u64>,
        /// Whether the session is currently connected.
        connected: bool,
    },
    /// Message history loaded for a channel.
    MessagesLoaded {
        /// Channel id.
        channel_id: String,
        /// Messages, oldest first.
        messages: Vec<ChatMessage>,
    },
    /// A message was created or updated (gateway or REST echo).
    ChatMessageUpsert {
        /// The message.
        message: ChatMessage,
    },
    /// A message was deleted.
    ChatMessageDeleted {
        /// Channel id.
        channel_id: String,
        /// Message id.
        message_id: String,
    },
    /// Someone started typing in a channel.
    TypingEvent {
        /// Channel id.
        channel_id: String,
        /// Username of the typist.
        user: String,
    },
    /// Bot voice connection state changed.
    VoiceUpdate {
        /// Current voice info.
        info: VoiceInfo,
    },
    /// Result of a guild-join attempt via invite link.
    InviteJoinResult {
        /// Whether the join succeeded.
        ok: bool,
        /// Joined guild name on success.
        guild_name: Option<String>,
        /// Error message on failure.
        error: Option<String>,
    },
    /// Channel list for a guild was fetched.
    ChannelsLoaded {
        /// Guild the channels belong to.
        guild_id: String,
        /// Channel entries.
        channels: Vec<ChannelEntry>,
    },
    /// Ping to repaint (clock, animations).
    Tick,
}

/// Everything loaded from storage on startup.
#[derive(Debug, Clone, Default)]
pub struct HydratedData {
    /// Preferences.
    pub prefs: Option<Preferences>,
    /// Layouts.
    pub layouts: Vec<Layout>,
    /// Notes.
    pub notes: Vec<Note>,
    /// Notifications.
    pub notifications: Vec<Notification>,
    /// Audit entries.
    pub audit_log: Vec<AuditEntry>,
    /// Widget instances grouped implicitly via layouts.
    pub widget_instances: Vec<PlacedWidget>,
}
